-- Tabla donde consumption-service guarda cada lectura recibida por Kafka
CREATE TABLE lectura (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    medidor_id  VARCHAR(32)      NOT NULL,
    momento     TIMESTAMPTZ      NOT NULL,
    kwh         DOUBLE PRECISION NOT NULL
);

-- Para las consultas de un contador en un rango de tiempo (coste diario)
CREATE INDEX idx_lectura_medidor_momento ON lectura (medidor_id, momento);

-- Para "las últimas 20 lecturas"
CREATE INDEX idx_lectura_momento ON lectura (momento DESC);